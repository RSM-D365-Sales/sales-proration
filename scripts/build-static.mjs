/**
 * Static build of the portal for one scenario — no server, no sign-in, deploys
 * to any static host (Cloudflare Pages).
 *
 *   node scripts/build-static.mjs sunset        → dist-sunset/
 *
 * What it does:
 *   1. backs up the previous build (dist-sunset → dist-sunset.prev)
 *   2. copies public/, then overlays scenarios/<key>/public/ (brand assets)
 *   3. bundles the scenario's data: data/snapshot.json + outbox.json (from
 *      scenarios/<key>/data — regenerate with the scenario's seed.mjs),
 *      branding.json and a trimmed scenario.json
 *   4. writes a static config.js (mode: 'static') and injects the shared
 *      modules + js/static-api.js into every page, so the same app.js answers
 *      /api/* in the browser from the bundled snapshot
 *   5. drops what a static, single-prospect bundle must not carry: Setup (no
 *      backend to configure), MSAL, other scenarios' brand assets
 *   6. writes a strict _headers (no external connect-src) and prints a
 *      reconciliation summary
 *
 * Never hand-edit the output — change public/ or scenarios/<key>/ and rebuild.
 */
import { readFileSync, writeFileSync, existsSync, rmSync, renameSync, cpSync, readdirSync, statSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, relative } from 'node:path'
import { createRequire } from 'node:module'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const key = process.argv[2]
if (!key) { console.error('usage: node scripts/build-static.mjs <scenario>'); process.exit(1) }
const scenDir = join(root, 'scenarios', key)
if (!existsSync(join(scenDir, 'scenario.json'))) { console.error(`Unknown scenario '${key}' (no scenarios/${key}/scenario.json)`); process.exit(1) }
const cfg = JSON.parse(readFileSync(join(scenDir, 'scenario.json'), 'utf8'))
const branding = JSON.parse(readFileSync(join(scenDir, 'branding.json'), 'utf8'))
const out = join(root, cfg.outDir || `dist-${key}`)

for (const f of ['snapshot.json', 'outbox.json']) {
  if (!existsSync(join(scenDir, 'data', f))) { console.error(`Missing scenarios/${key}/data/${f} — run: node scenarios/${key}/seed.mjs`); process.exit(1) }
}

// 1. back up the last build
if (existsSync(out)) {
  const prev = out + '.prev'
  if (existsSync(prev)) rmSync(prev, { recursive: true, force: true })
  renameSync(out, prev)
}

// 2. app + scenario overlay
cpSync(join(root, 'public'), out, { recursive: true })
if (existsSync(join(scenDir, 'public'))) cpSync(join(scenDir, 'public'), out, { recursive: true })

// 5. strip what this bundle must not carry
const drop = ['setup.html', 'js/setup.js', 'js/vendor']
for (const d of drop) rmSync(join(out, d), { recursive: true, force: true })
// The ribbon layout ships as a neutral skin-ribbon.css (comments stripped —
// they describe the show brand it was first drawn for).
const ribbonCss = readFileSync(join(out, 'styles', 'skin-bluestem.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/\n{3,}/g, '\n\n')
  .replaceAll(':root:is([data-theme="bluestem"], [data-theme="sunset"])', `:root[data-theme="${branding.theme}"]`)
writeFileSync(join(out, 'styles', 'skin-ribbon.css'), `/* Shared top-ribbon layout (generated from public/styles/skin-bluestem.css). */\n${ribbonCss.trim()}\n`)
rmSync(join(out, 'styles', 'skin-bluestem.css'))
const brandDir = join(out, 'img', 'brand')
const keepBrand = new Set([branding.logo, branding.favicon, branding.sponsor?.logo].filter(Boolean).map(p => p.replace(/^img\/brand\//, '')))
for (const f of readdirSync(brandDir)) if (!keepBrand.has(f)) rmSync(join(brandDir, f))

// 3. data
mkdirSync(join(out, 'data'), { recursive: true })
cpSync(join(scenDir, 'data', 'snapshot.json'), join(out, 'data', 'snapshot.json'))
cpSync(join(scenDir, 'data', 'outbox.json'), join(out, 'data', 'outbox.json'))
writeFileSync(join(out, 'data', 'branding.json'), JSON.stringify(branding, null, 2) + '\n')
const { key: _k, outDir: _o, pagesProject: _p, seed: _s, $comment: _c, ...publicCfg } = cfg
writeFileSync(join(out, 'data', 'scenario.json'), JSON.stringify(publicCfg, null, 2) + '\n')

// 4. static config + page wiring
writeFileSync(join(out, 'config.js'), `// Generated by scripts/build-static.mjs (${key}) — do not edit.
// Static build: no API server and no sign-in. js/static-api.js answers /api/*
// in the browser from data/snapshot.json; sends are recorded, not transmitted.
window.APP_CONFIG = {
  mode: 'static',
  scenario: ${JSON.stringify(key)},
  apiBase: '',
  auth: { tenantId: '', clientId: '', apiScope: '' },
};
`)

const SHARED = ['js/shared/proration.js', 'js/shared/snapshot.js', 'js/shared/messages.js', 'js/shared/subs.js', 'js/shared/portal-core.js', 'js/static-api.js']
const pages = readdirSync(out).filter(f => f.endsWith('.html'))
for (const page of pages) {
  let html = readFileSync(join(out, page), 'utf8')
  html = html.replace(/\s*<script src="js\/vendor\/msal-browser\.min\.js"><\/script>/, '')
  html = html.replace('href="styles/skin-bluestem.css"', 'href="styles/skin-ribbon.css"')
  // Drop later duplicates of the shared modules, then inject the full set right after auth.js.
  for (const src of SHARED) html = html.replace(new RegExp(`\\s*<script src="${src.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}"></script>`, 'g'), '')
  if (!html.includes('<script src="js/auth.js"></script>')) throw new Error(`${page}: no auth.js script tag to anchor on`)
  html = html.replace('<script src="js/auth.js"></script>',
    '<script src="js/auth.js"></script>\n' + SHARED.map(s => `  <script src="${s}"></script>`).join('\n'))
  // First paint in the scenario's skin even before the branding cache exists.
  html = html.replace('<html lang="en">', `<html lang="en" data-theme="${branding.theme}">`)
  if (branding.favicon) html = html.replace('</title>', `</title>\n  <link rel="icon" href="${branding.favicon}" type="${branding.favicon.endsWith('.svg') ? 'image/svg+xml' : 'image/png'}" />`)
  writeFileSync(join(out, page), html)
}

// 6. headers — nothing external to connect to
writeFileSync(join(out, '_headers'), `# Generated by scripts/build-static.mjs (${key}). Static build: every request
# stays on this origin.
/*
  Content-Security-Policy: default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; font-src 'self'; connect-src 'self'; frame-ancestors 'none'; base-uri 'self'; form-action 'self'
  X-Frame-Options: DENY
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()

/js/*
  Cache-Control: public, max-age=0, must-revalidate
/styles/*
  Cache-Control: public, max-age=0, must-revalidate
/data/*
  Cache-Control: public, max-age=0, must-revalidate
/config.js
  Cache-Control: public, max-age=0, must-revalidate
`)

// Reconciliation summary
const { normalizeSnapshot } = require('../public/js/shared/snapshot.js')
const core = require('../public/js/shared/portal-core.js')
const raw = JSON.parse(readFileSync(join(out, 'data', 'snapshot.json'), 'utf8'))
const snap = normalizeSnapshot(raw)
const rows = core.listCommodities(snap)
const td = rows.reduce((s, r) => s + r.totalDemand, 0), ts = rows.reduce((s, r) => s + r.totalSupply, 0)
const lineSum = snap.demand.reduce((s, d) => s + d.requestedQty, 0)
const walk = d => readdirSync(d).flatMap(f => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]))
const files = walk(out)
const bytes = files.reduce((s, f) => s + statSync(f).size, 0)
const stray = files.filter(f => /bluestem|msal/i.test(relative(out, f)))

console.log(`\nStatic build · scenario ${key} → ${relative(root, out)}/`)
console.log(`  snapshot as of ${raw.asOf}${cfg.rebaseDates ? ' (re-anchored to the viewer\'s today at load)' : ''} · company ${cfg.company}`)
console.log(`  ${rows.length} buyer groups · ${snap.items.length} items · ${snap.customers.length} customers · ${snap.demand.length} lines · ${snap.substitutions.length} rules`)
console.log(`  demand ${td.toLocaleString()} · supply ${ts.toLocaleString()} · fill ${((ts / td) * 100).toFixed(1)}% · ${rows.map(r => `${r.name} ${r.status}`).join(' · ')}`)
console.log(`  tie-out: demand lines ${lineSum.toLocaleString()} ${lineSum === td ? '= buyer-group demand ✓' : '≠ buyer-group demand ✗'}`)
console.log(`  ${pages.length} pages · ${files.length} files · ${(bytes / 1024).toFixed(0)} KB${stray.length ? ` · ✗ stray files: ${stray.map(f => relative(out, f)).join(', ')}` : ' · no other-scenario assets ✓'}`)
console.log(`  deploy: npx wrangler pages deploy ${relative(root, out)} --project-name=${cfg.pagesProject} --branch=main\n`)
if (lineSum !== td || stray.length) process.exit(1)
